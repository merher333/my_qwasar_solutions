#include <stdio.h>

int main() {
    int my_age = 34;               // Integer variable
    char my_name[] = "Luke";       // String (array of characters)
    char my_comma = ',';           // Character variable

    printf("Hello %s%c I'm %d years old.\n", my_name, my_comma, my_age); // Print variables
    return 0;
}
